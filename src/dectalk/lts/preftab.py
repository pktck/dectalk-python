"""LTS prefix table.

Translated from ``src/dapi/src/lts/l_us_con.c``. ``preftab`` is consulted
by ``ls_adju.c::ls_adju_pre`` after the rule pass: it pattern-matches
the first few phonemes of a word against canonical prefixes and applies
prefix-specific adjustments (stress reset, second-syllable hint, R-coloring
of the following vowel, etc.) before the word continues through the
duration / intonation stages.

Record format:

    <size + flags>      one byte; low 4 bits = phoneme count, high bits
                        encode prefix-feature flags (PCONT/P2SYL/PRCON)
    <phonemes>...       phoneme codes (count = low nibble of size byte)

Feature bits in the size byte:
    - :data:`PCONT` 0x10 — prefix continues into the body (not isolating)
    - :data:`PRCON` 0x20 — R-colored vowel follows
    - :data:`P2SYL` 0x80 — affects the second syllable's stress

The table terminates with a single 0 byte after the last record.

Sample entries (see C source for the full list):
    AB, ANDR (with PCONT+P2SYL), AN (PCONT), BAYD, BAYK, ..., FOR, KAN,
    INT, IN, MIS, NAN, OVR (PCONT+P2SYL), PRAA, PRIY, RE (PCONT+PRCON),
    SUP, SUS, TRANS, WITH.
"""

