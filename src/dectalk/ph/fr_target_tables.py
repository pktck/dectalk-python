"""Number of columns per phoneme in ``Cibles_*`` (``N_PARAM`` in C)."""


def cibles_flat(cibles: tuple[tuple[int, ...], ...]) -> list[int]:
    """Flatten a 2D ``Cibles_*`` table to a 1D list (row-major, C order).

    ``fr_gettar`` indexes ``Cibles_Defaut`` as a flat array via
    ``Cibles_Defaut[phoneme * N_PARAM + col]`` (mirroring the C cast
    ``(short *)Cibles_MALE``); this helper produces the corresponding
    row-major linear view.
    """
    flat: list[int] = []
    for row in cibles:
        flat.extend(row)
    return flat


