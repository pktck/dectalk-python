"""US English PH ROM tables (phoneme-target voice definitions).

Translated from ``src/dapi/src/ph/p_us_rom.c`` and (for the
duration-critical entries ``us_inhdr`` / ``us_mindur``) from
``src/dapi/src/ph/p_us_rom_dectalk_1996m_43f.c`` — the latter being
the active voice ROM selected by ``dectalkf_klsyn.h:296``
(``#define VOICE_ROM_DECTALK_1996M_43F``). ``ph_romi.c`` then
``#include``s that file rather than ``p_us_rom.c``.

The 1996m_43f vs p_us_rom split matters for byte-identical PH output.
The per-allophone duration tables differ (e.g. HX inhdr = 70 in
1996m_43f vs 80 in p_us_rom; AX = 120 vs 160), and so do the formant /
bandwidth / locus *target* tables. The latter were re-ported from the
active ROM (issue #229): :data:`us_maltar`, :data:`us_femtar`,
:data:`us_maldip`, :data:`us_femdip`, :data:`us_maleloc`,
:data:`us_femloc`, and :data:`us_plocu` now mirror
``p_us_rom_dectalk_1996m_43f.c`` byte-for-byte (with its in-table C
arithmetic such as ``180+80`` / ``300+100`` evaluated). Critically, the
active ROM uses ``US_TOT_ALLOPHONES == 57`` (not the BETA5 ``71``), so
those target/locus tables are laid out in 57-phone blocks;
:func:`dectalk.ph.us_gettar.us_gettar` and
:func:`dectalk.ph.setloc.setloc` stride by 57 to match.

The amplitude tables (:data:`us_malamp` / :data:`us_femamp` /
:data:`us_ptram`) and the per-phone gesture/prosody tables
(:data:`us_burdr`, :data:`us_f0segtars`, :data:`us_endtyp`) were
re-ported from the active ROM as well (issue #235). The active
amplitude ROM differs structurally from BETA5: it lays each obstruent
out as a 4-row x 6-column block (24 entries) referenced by a 24-stride
:data:`us_ptram` base offset, rather than the BETA5 30-stride layout
with ``-1`` sentinels, and applies in-table reductions (``49-6``,
``65-10``) plus a ``DEC_SZ`` reduction on the S/Z A5 entries.
``dectalkf_klsyn.h`` line 300 defines ``DEC_SZ 3`` whenever a
``VOICE_ROM_*`` is selected -- which the active build always does --
so the compiled S/Z amplitudes are 3 dB below the in-table literals
(issue #269; an earlier pass resolved the macro to 0).

These phoneme-indexed lookup tables drive the Klatt-frame
target generation in the PH module — feeding into the
duration/F0/formant trajectory synthesis that produces what gets
handed to the HLSYN synthesizer.

Per-phoneme tables (71 entries — codes 0..56 active, 57..70 sentinel
padding — indexed by allophone code from
:class:`dectalk.include.phoneme_codes.USPhoneme`):

- :data:`us_inhdr` — inherent duration in samples
- :data:`us_mindur` — minimum duration in samples
- :data:`us_burdr` — burst duration
- :data:`us_f0segtars` — F0 segment targets
- :data:`us_begtyp` / :data:`us_endtyp` — begin/end gesture type
- :data:`us_place` — place of articulation
- :data:`us_ptram` — phoneme-transition-amplitude
- :data:`us_featb` — additional per-phoneme feature byte (105 entries,
  re-ported from the active ROM; voice-ROM-dependent)

Per-phoneme matrices (per-phoneme blocks of feature-vector
sub-tables):

- :data:`us_maltar` / :data:`us_femtar` — male / female F1-F3
  formant target frequencies + B1-B3 bandwidths + AV (399 entries =
  57 phones x 7 parameter blocks)
- :data:`us_maldip` / :data:`us_femdip` — male / female formant
  diphthong-transition values (450 entries; flat, referenced by the
  negative sentinels in ``us_maltar`` / ``us_femtar``)
- :data:`us_malamp` / :data:`us_femamp` — male / female parallel-branch
  amplitude envelopes (385 entries = 1 SIL slot + 16 obstruents x 4
  rows x 6 columns), indexed via :data:`us_ptram` base offsets
- :data:`us_plocu` — per-phone locus pointers (171 entries = 57 x
  FRONT/BACK/ROUND)
- :data:`us_maleloc` / :data:`us_femloc` — male / female formant
  locus targets (478 entries; flat, indexed via ``us_plocu``)

Global prosody knobs:

- :data:`us_f0glstp` — glottal-stop F0 step ladder (6 entries)
- :data:`us_f0_phrase_position` — F0 multiplier by phrase position
- :data:`us_f0_stress_level` — F0 multiplier by stress level
"""

