def dt_f_log10(input_: float) -> float:
    """Return ``log10(input_)`` via the log10table lookup.

    Faithful translation of:

    .. code-block:: c

        float DT_f_log10(float input) {
            int pos;
            if (input > 100.0f) return (float)(log10(input));
            if (input > 10.0f)  {
                pos = (int)(input * 10.0f);
                return log10table[pos] + 1;
            }
            pos = (int)(input * 100.0f);
            return log10table[pos];
        }

    The two table branches use different index scales so the same
    1001-entry table covers both decades:

    - ``input > 100.0``: fall through to :func:`math.log10`.
    - ``10.0 < input <= 100.0``: ``pos = int(input * 10.0)``;
      return ``log10table[pos] + 1``.
    - ``input <= 10.0``: ``pos = int(input * 100.0)``;
      return ``log10table[pos]``.

    Args:
        input_: Value to find the base-10 logarithm of. Must be
            positive for the fall-through branch; the table branches
            silently accept zero / negatives (returning the table's
            lower-bound placeholder), matching the C source.

    Returns:
        ``log10(input_)`` either via the table or via
        :func:`math.log10`.
    """
    if input_ > 100.0:  # noqa: PLR2004 - branch threshold from C source
        return math.log10(input_)
    if input_ > 10.0:  # noqa: PLR2004 - branch threshold from C source
        pos = int(input_ * 10.0)
        return log10table[pos] + 1
    pos = int(input_ * 100.0)
    return log10table[pos]


